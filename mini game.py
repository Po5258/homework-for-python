def validate_answer(user_input, correct_index):
    cleaned = re.sub(r'\s+', '', user_input)
    if not cleaned.isdigit():
        return False, "Ошибка: введено не число. Ответ не засчитан."
    if int(cleaned) == correct_index:
        return True, "Верно! Это ложь."
    return False, f"Неверно. Ложью был факт под номером {correct_index}."


def play_game():
    questions = get_fandom_questions()
    random.shuffle(questions)
    score = 0

    print("=== УГАДАЙ ПО ФАНДОМУ ===")
    print("Я называю объект и даю 3 факта. Один из них - ложь. Найди её!\n")

    for q in questions:
        print(f"Объект: {q['object']}")
        for i, clue in enumerate(q['clues'], 1):
            print(f"{i}. {clue}")

        user_answer = input("Введи номер ложного факта (1-3): ")
        is_correct, message = validate_answer(user_answer, q['lie_index'])

        print(message + "\n")
        if is_correct:
            score += 1

    print(f"Игра окончена! Твой счет: {score} из {len(questions)}")


if __name__ == "__main__":
    play_game()